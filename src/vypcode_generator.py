"""
VYPcode Generator for VYPlanguage
Generates VYPcode assembly from intermediate representation
"""

from typing import List, Dict, Any, Optional
from intermediate_representation import IRInstruction, IRType

class VYPcodeGenerator:
    """Generates VYPcode assembly from IR"""
    
    def __init__(self):
        self.output_lines = []
        self.label_map = {}
        self.temp_map = {}
        self.register_map = {}
        self.string_constants = {}
        self.next_string_id = 1
        self.next_label_id = 1
        self.current_register = 0
        self.max_registers = 8
        
    def new_label(self) -> str:
        """Generate a new label"""
        label = f"L{self.next_label_id}"
        self.next_label_id += 1
        return label
    
    def new_string_constant(self, value: str) -> str:
        """Generate a new string constant"""
        if value in self.string_constants:
            return self.string_constants[value]
        
        string_id = f"str_{self.next_string_id}"
        self.next_string_id += 1
        self.string_constants[value] = string_id
        return string_id
    
    def get_register(self) -> str:
        """Get next available register"""
        reg = f"${self.current_register}"
        self.current_register = (self.current_register + 1) % self.max_registers
        return reg
    
    def generate(self, instructions: List[IRInstruction]) -> str:
        """Generate VYPcode from IR instructions"""
        self.output_lines = []
        self.label_map = {}
        self.temp_map = {}
        self.register_map = {}
        self.string_constants = {}
        self.next_string_id = 1
        self.next_label_id = 1
        self.current_register = 0
        
        # Add VYPcode header
        self.output_lines.append("#! /bin/vypint")
        self.output_lines.append("# VYPcode: 1.0")
        self.output_lines.append("# Generated by: VYPlanguage Compiler")
        self.output_lines.append("")
        
        # First pass: collect labels, temporaries, and string constants
        self._collect_labels_and_temps(instructions)
        
        # Add string constants section
        if self.string_constants:
            self.output_lines.append("# String constants")
            for value, string_id in self.string_constants.items():
                self.output_lines.append(f"CONSTANT {string_id} \"{value}\"")
            self.output_lines.append("")
        
        # Add labels and generate instructions
        self._collect_labels_and_temps(instructions)
        
        # Generate main label
        self.output_lines.append("LABEL main")
        
        # Generate instructions
        for instruction in instructions:
            self._generate_instruction(instruction)
        
        # Add program end
        self.output_lines.append("RETURN $0")
        
        return '\n'.join(self.output_lines)
    
    def _collect_labels_and_temps(self, instructions: List[IRInstruction]):
        """Collect all labels, temporaries, and string constants"""
        temp_counter = 0
        
        for instruction in instructions:
            if instruction.type == IRType.LABEL:
                self.label_map[instruction.label] = f"label_{instruction.label}"
            
            # Map temporary variables to registers
            if instruction.result and instruction.result.startswith('t'):
                if instruction.result not in self.temp_map:
                    temp_counter += 1
                    self.temp_map[instruction.result] = self.get_register()
            
            # Collect string constants from function calls
            if instruction.type == IRType.FUNCTION_CALL and instruction.arg1 == "print":
                args = instruction.arg2 if instruction.arg2 else []
                for arg in args:
                    if isinstance(arg, tuple) and arg[0] == 'primary' and isinstance(arg[1], str) and arg[1].startswith('"'):
                        # String literal from primary
                        self.new_string_constant(arg[1][1:-1])
    
    def _generate_instruction(self, instruction: IRInstruction):
        """Generate VYPcode for a single instruction"""
        if instruction.type == IRType.ASSIGN:
            result = self._get_operand(instruction.result)
            arg1 = self._get_operand(instruction.arg1)
            self.output_lines.append(f"SET {result}, {arg1}")
        
        elif instruction.type == IRType.BINARY_OP:
            result = self._get_operand(instruction.result)
            arg1 = self._get_operand(instruction.arg1)
            arg2 = self._get_operand(instruction.arg2)
            
            # Map operators to VYPcode instructions
            op_map = {
                '+': 'ADDI',
                '-': 'SUBI', 
                '*': 'MULI',
                '/': 'DIVI',
                '==': 'EQI',
                '!=': 'NEI',
                '<': 'LTI',
                '>': 'GTI',
                '<=': 'LEI',
                '>=': 'GEI',
                '&&': 'AND',
                '||': 'OR'
            }
            
            if instruction.op in op_map:
                self.output_lines.append(f"{op_map[instruction.op]} {result}, {arg1}, {arg2}")
            else:
                self.output_lines.append(f"# Unknown operator: {instruction.op}")
        
        elif instruction.type == IRType.UNARY_OP:
            result = self._get_operand(instruction.result)
            arg1 = self._get_operand(instruction.arg1)
            
            if instruction.op == '!':
                self.output_lines.append(f"NOT {result}, {arg1}")
            elif instruction.op == '-':
                self.output_lines.append(f"SUBI {result}, 0, {arg1}")
        
        elif instruction.type == IRType.JUMP:
            label = self.label_map.get(instruction.label, instruction.label)
            self.output_lines.append(f"JUMP {label}")
        
        elif instruction.type == IRType.CONDITIONAL_JUMP:
            arg1 = self._get_operand(instruction.arg1)
            arg2 = self._get_operand(instruction.arg2)
            label = self.label_map.get(instruction.label, instruction.label)
            
            if instruction.op == "==":
                self.output_lines.append(f"JUMPZ {label}, {arg1}")
            elif instruction.op == "!=":
                self.output_lines.append(f"JUMPNZ {label}, {arg1}")
            else:
                self.output_lines.append(f"# Conditional jump: {instruction.op}")
        
        elif instruction.type == IRType.LABEL:
            label = self.label_map.get(instruction.label, instruction.label)
            self.output_lines.append(f"LABEL {label}")
        
        elif instruction.type == IRType.FUNCTION_CALL:
            result = self._get_operand(instruction.result)
            func_name = instruction.arg1
            args = instruction.arg2 if instruction.arg2 else []
            
            # Handle embedded functions
            if func_name == "print":
                for arg in args:
                    arg_val = self._get_operand(arg)
                    if isinstance(arg, str) and arg.startswith('"'):
                        # String literal
                        string_id = self.new_string_constant(arg[1:-1])
                        self.output_lines.append(f"WRITES {string_id}")
                    elif isinstance(arg, tuple) and arg[0] == 'primary' and isinstance(arg[1], str) and arg[1].startswith('"'):
                        # String literal from primary
                        string_id = self.new_string_constant(arg[1][1:-1])
                        self.output_lines.append(f"WRITES {string_id}")
                    else:
                        # Integer or variable
                        self.output_lines.append(f"WRITEI {arg_val}")
            elif func_name == "readInt":
                self.output_lines.append(f"READI {result}")
            elif func_name == "readString":
                self.output_lines.append(f"READS {result}")
            else:
                # User-defined function call
                self.output_lines.append(f"CALL $SP, {func_name}")
        
        elif instruction.type == IRType.RETURN:
            if instruction.arg1:
                arg1 = self._get_operand(instruction.arg1)
                self.output_lines.append(f"SET $0, {arg1}")
            self.output_lines.append("RETURN $0")
        
        elif instruction.type == IRType.PRINT:
            arg1 = self._get_operand(instruction.arg1)
            if isinstance(instruction.arg1, str) and instruction.arg1.startswith('"'):
                # String literal
                string_id = self.new_string_constant(instruction.arg1[1:-1])
                self.output_lines.append(f"WRITES {string_id}")
            else:
                # Integer
                self.output_lines.append(f"WRITEI {arg1}")
        
        elif instruction.type == IRType.READ:
            result = self._get_operand(instruction.result)
            self.output_lines.append(f"READI {result}")
    
    def _get_operand(self, operand):
        """Get the VYPcode operand representation"""
        if operand is None:
            return "0"
        elif isinstance(operand, (int, float)):
            return str(operand)
        elif isinstance(operand, str):
            if operand.startswith('t') and operand in self.temp_map:
                return self.temp_map[operand]
            elif operand.startswith('"') and operand.endswith('"'):
                # String literal - will be handled by string constants
                return operand
            else:
                # Variable name - map to register
                if operand not in self.register_map:
                    self.register_map[operand] = self.get_register()
                return self.register_map[operand]
        else:
            return str(operand)

