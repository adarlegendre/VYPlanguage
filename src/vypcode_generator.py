from typing import List, Dict, Any, Optional, Set
from intermediate_representation import IRInstruction, IRType
from class_model import ClassInfo, class_declaration_order, HEADER_SIZE


def _escape_vyp_string(value: str) -> str:
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    return "".join(out)


class VYPcodeGenerator:
    """Stack-frame VYPcode generator with string runtime helpers."""

    def __init__(self):
        self.output_lines: List[str] = []
        self.slots: Dict[str, str] = {}
        self.types: Dict[str, str] = {}  # name -> int|string|class
        self.param_count = 0
        self.return_type = "void"
        self.current_func: Optional[str] = None
        self.func_meta: Dict[str, dict] = {}
        self.need_concat = False
        self.need_length = False
        self.need_substr = False
        self.classes: Dict[str, ClassInfo] = {}
        self.class_order: List[str] = []
        self._label_counter = 0

    def _fresh_label(self, prefix: str = "L") -> str:
        self._label_counter += 1
        return f"__{prefix}_{self._label_counter}"

    def _is_subclass_of(self, name: str, target: str) -> bool:
        """True if name is target or inherits from target."""
        cur = self.classes.get(name)
        while cur is not None:
            if cur.name == target:
                return True
            cur = cur.parent
        return False

    def _runtime_cast_names(self, target: str) -> List[str]:
        """Class names whose runtime instances may be cast to target."""
        return [
            name
            for name in self.class_order
            if self._is_subclass_of(name, target)
        ]

    def _emit(self, line: str = ""):
        self.output_lines.append(line)

    def generate(
        self, instructions: List[IRInstruction], classes: Dict[str, ClassInfo] = None
    ) -> str:
        self.output_lines = []
        self.func_meta = {}
        self.need_concat = False
        self.need_length = False
        self.need_substr = False
        self._label_counter = 0
        self.classes = classes or {}
        self.class_order = class_declaration_order(self.classes) if self.classes else []
        self._index_functions(instructions)
        self._scan_helpers(instructions)

        self._emit("#! /bin/vypint")
        self._emit("# VYPcode: 1.0")
        self._emit("# Generated by: VYPlanguage Compiler")
        self._emit()
        self._emit("ALIAS BP $0")
        self._emit("ALIAS AX $1")
        self._emit("ALIAS BX $2")
        self._emit("ALIAS CX $3")
        self._emit("ALIAS OBJ $4")
        self._emit("ALIAS EX $5")
        self._emit("ALIAS SI $6")
        self._emit("ALIAS DI $7")
        self._emit()

        # Emit VMTs onto the stack before calling main (indices = class_order)
        for cname in self.class_order:
            self._emit_vmt(cname)

        self._emit("# Program entry")
        self._emit("SET $BP, $SP")
        self._emit("CALL [$SP+1], main")
        self._emit("JUMP _end")
        self._emit()

        i = 0
        while i < len(instructions):
            ins = instructions[i]
            if ins.type == IRType.FUNCTION_DEF:
                i = self._emit_function(instructions, i)
            else:
                self._generate_instruction(ins)
                i += 1

        self._emit_object_helpers()
        if self.need_length:
            self._emit_length_helper()
        if self.need_substr:
            self._emit_substr_helper()
        if self.need_concat:
            self._emit_concat_helper()

        self._emit("LABEL _end")
        return "\n".join(self.output_lines) + "\n"

    def _emit_vmt(self, class_name: str):
        info = self.classes[class_name]
        vmt = info.vmt()
        methods = list(vmt.values())
        self._emit(f"# VMT for {class_name}")
        self._emit(f"CREATE $AX, {len(methods)}")
        for i, method in enumerate(methods):
            self._emit(f'SETWORD $AX, {i}, "{method.label}"')
        self._emit("SET [$SP], $AX")
        self._emit("ADDI $SP, $SP, 1")
        self._emit()

    def _scan_helpers(self, instructions: List[IRInstruction]):
        for ins in instructions:
            if ins.type == IRType.BINARY_OP and ins.op == "CONCAT":
                self.need_concat = True
            if ins.type == IRType.FUNCTION_CALL:
                if ins.arg1 == "length":
                    self.need_length = True
                elif ins.arg1 == "subStr":
                    self.need_substr = True

    def _index_functions(self, instructions: List[IRInstruction]):
        current = None
        temps: Set[str] = set()
        for ins in instructions:
            if ins.type == IRType.FUNCTION_DEF:
                if current is not None:
                    self.func_meta[current]["temps"] = sorted(temps)
                current = ins.arg1
                meta = dict(ins.arg2 or {})
                meta["temps"] = []
                self.func_meta[current] = meta
                temps = set()
            else:
                for val in (ins.result, ins.arg1, ins.arg2):
                    self._collect_temp_names(val, temps)
        if current is not None:
            self.func_meta[current]["temps"] = sorted(temps)

    def _collect_temp_names(self, val: Any, temps: set):
        if isinstance(val, str) and val.startswith("t") and val[1:].isdigit():
            temps.add(val)
        elif isinstance(val, tuple) and val[0] == "var":
            name = val[1]
            if isinstance(name, str) and name.startswith("t") and name[1:].isdigit():
                temps.add(name)
        elif isinstance(val, list):
            for item in val:
                self._collect_temp_names(item, temps)

    def _emit_function(self, instructions: List[IRInstruction], start: int) -> int:
        ins = instructions[start]
        name = ins.arg1
        meta = self.func_meta[name]
        params = list(meta.get("params") or [])
        locals_list = list(meta.get("locals") or [])
        local_types = dict(meta.get("local_types") or {})
        temps = list(meta.get("temps") or [])
        self.return_type = meta.get("return_type") or "void"
        self.param_count = len(params)
        self.current_func = name

        self.slots = {}
        self.types = {}
        class_name = meta.get("class_name")
        n = len(params)
        for idx, pname in enumerate(params):
            self.slots[pname] = f"[$BP-{1 + n - idx}]"
            if pname == "this" and class_name:
                self.types[pname] = class_name
            else:
                self.types[pname] = local_types.get(pname, "int")
        offset = 1
        for lname in locals_list:
            self.slots[lname] = f"[$BP+{offset}]"
            self.types[lname] = local_types.get(lname, "int")
            offset += 1
        for tname in temps:
            if tname not in self.slots:
                self.slots[tname] = f"[$BP+{offset}]"
                self.types[tname] = "int"
                offset += 1
        local_slots = offset - 1

        self._emit(f"LABEL {name}")
        self._emit("ADDI $SP, $SP, 1")
        self._emit("ADDI $SP, $SP, 1")
        self._emit("SET [$SP], $BP")
        self._emit("SET $BP, $SP")
        for _ in range(local_slots):
            self._emit("ADDI $SP, $SP, 1")
            self._emit("SET [$SP], 0")

        i = start + 1
        while i < len(instructions) and instructions[i].type != IRType.FUNCTION_DEF:
            self._update_types_from_ins(instructions[i])
            self._generate_instruction(instructions[i])
            i += 1

        # Spec §4.6: falling off the end returns a type default (0 / "" / null).
        # Always emit this epilogue so paths without an explicit return still exit.
        if self.return_type == "void":
            self._emit_epilogue(None)
        elif self.return_type == "string":
            self._materialize_string("", "$AX")
            self._emit_epilogue("$AX")
        else:
            self._emit_epilogue("0")

        self._emit()
        self.current_func = None
        return i

    def _update_types_from_ins(self, ins: IRInstruction):
        if ins.type == IRType.ASSIGN and ins.result:
            self.types[ins.result] = self._type_of(ins.arg1)
        elif ins.type == IRType.BINARY_OP and ins.result:
            if ins.op == "CONCAT":
                self.types[ins.result] = "string"
            elif ins.op in ("EQS", "NES", "LTS", "GTS", "LES", "GES"):
                self.types[ins.result] = "int"
            else:
                self.types[ins.result] = "int"
        elif ins.type == IRType.FUNCTION_CALL and ins.result:
            if ins.arg1 == "readString" or ins.arg1 == "subStr":
                self.types[ins.result] = "string"
            elif ins.arg1 in self.func_meta:
                self.types[ins.result] = self.func_meta[ins.arg1].get(
                    "return_type", "int"
                )
            else:
                self.types[ins.result] = "int"
        elif ins.type == IRType.UNARY_OP and ins.result:
            if ins.op and ins.op.startswith("CAST_"):
                self.types[ins.result] = ins.op[5:]
            else:
                self.types[ins.result] = "int"
        elif ins.type == IRType.NEW and ins.result:
            self.types[ins.result] = ins.arg1
        elif ins.type == IRType.FIELD_GET and ins.result:
            info = self._resolve_field_class(ins.arg1)
            if info:
                self.types[ins.result] = info.all_fields().get(ins.arg2, "int")
        elif ins.type == IRType.METHOD_CALL and ins.result:
            meta = ins.arg2 or {}
            static_type = meta.get("static_type") or "Object"
            info = self.classes.get(static_type)
            if info:
                if meta.get("super") and info.parent:
                    meth = info.parent.vmt().get(ins.op)
                else:
                    meth = info.vmt().get(ins.op)
                if meth:
                    self.types[ins.result] = meth.return_type

    def _ret_area(self) -> int:
        return max(self.param_count, 1)

    def _return_slot(self) -> str:
        n = self._ret_area()
        return f"[$BP-{1 + n}]"

    def _emit_epilogue(self, return_src: Optional[str]):
        n = self._ret_area()
        if return_src is not None and self.return_type != "void":
            self._emit(f"SET {self._return_slot()}, {return_src}")
        elif self.return_type != "void" and return_src is None:
            self._emit(f"SET {self._return_slot()}, 0")
        self._emit("SET $SP, $BP")
        self._emit("SET $BP, [$SP]")
        self._emit("SUBI $SP, $SP, 1")
        self._emit(f"SUBI $SP, $SP, {n}")
        self._emit(f"RETURN [$SP+{n}]")

    def _type_of(self, value: Any) -> str:
        if isinstance(value, tuple):
            if value[0] == "int_lit":
                return "int"
            if value[0] == "str_lit":
                return "string"
            if value[0] == "var":
                return self.types.get(value[1], "int")
        if isinstance(value, str):
            return self.types.get(value, "int")
        if isinstance(value, int):
            return "int"
        return "int"

    def _is_str_lit(self, value: Any) -> bool:
        return isinstance(value, tuple) and value[0] == "str_lit"

    def _materialize_string(self, text: str, dest_reg: str = "$AX"):
        escaped = _escape_vyp_string(text)
        self._emit(f"CREATE {dest_reg}, 1")
        self._emit(f'SETWORD {dest_reg}, 0, "{escaped}"')
        self._emit(f"GETWORD {dest_reg}, {dest_reg}, 0")

    def _load_to_reg(self, value: Any, reg: str = "$AX") -> str:
        if self._is_str_lit(value):
            self._materialize_string(value[1], reg)
            return reg
        if isinstance(value, tuple) and value[0] == "int_lit":
            self._emit(f"SET {reg}, {value[1]}")
            return reg
        if isinstance(value, tuple) and value[0] == "var":
            self._emit(f"SET {reg}, {self.slots[value[1]]}")
            return reg
        if isinstance(value, int):
            self._emit(f"SET {reg}, {value}")
            return reg
        if isinstance(value, str):
            self._emit(f"SET {reg}, {self.slots[value]}")
            return reg
        return str(value)

    def _operand(self, value: Any) -> str:
        """Addressing form without forcing a load (imm / stack)."""
        if self._is_str_lit(value):
            return None  # caller must materialize
        if isinstance(value, tuple):
            if value[0] == "int_lit":
                return str(value[1])
            if value[0] == "var":
                return self.slots[value[1]]
        if isinstance(value, int):
            return str(value)
        if isinstance(value, str):
            return self.slots[value]
        return str(value)

    def _generate_instruction(self, instruction: IRInstruction):
        if instruction.type == IRType.LABEL:
            self._emit(f"LABEL {instruction.label}")
            return

        if instruction.type == IRType.ASSIGN:
            dst = self.slots[instruction.result]
            dst_type = self.types.get(instruction.result) or self._type_of(
                instruction.arg1
            )
            if self._is_str_lit(instruction.arg1):
                self._materialize_string(instruction.arg1[1], "$AX")
                # Spec: string variables are assigned by value (COPY)
                self._emit("COPY $BX, $AX")
                self._emit(f"SET {dst}, $BX")
            elif dst_type == "string":
                src = self._load_to_reg(instruction.arg1, "$AX")
                self._emit(f"COPY $BX, {src}")
                self._emit(f"SET {dst}, $BX")
            else:
                src = self._operand(instruction.arg1)
                if src is None:
                    self._load_to_reg(instruction.arg1, "$AX")
                    self._emit(f"SET {dst}, $AX")
                else:
                    self._emit(f"SET {dst}, {src}")

        elif instruction.type == IRType.BINARY_OP:
            self._emit_binary(instruction)

        elif instruction.type == IRType.UNARY_OP:
            dst = self.slots[instruction.result]
            if instruction.op and instruction.op.startswith("CAST_"):
                target = instruction.op[5:]
                src = self._load_to_reg(instruction.arg1, "$AX")
                if target == "string":
                    self._emit(f"INT2STRING $AX, {src}")
                    self._emit(f"SET {dst}, $AX")
                elif target in self.classes:
                    self._emit_dynamic_cast(src, target, dst)
                else:
                    self._emit(f"SET {dst}, {src}")
            else:
                a = self._load_to_reg(instruction.arg1, "$AX")
                if instruction.op == "!":
                    self._emit(f"NOT $AX, {a}")
                elif instruction.op == "-":
                    self._emit(f"SUBI $AX, 0, {a}")
                else:
                    raise RuntimeError(f"Unsupported unary: {instruction.op}")
                self._emit(f"SET {dst}, $AX")

        elif instruction.type == IRType.JUMP:
            self._emit(f"JUMP {instruction.label}")

        elif instruction.type == IRType.CONDITIONAL_JUMP:
            cond = self._load_to_reg(instruction.arg1, "$AX")
            if instruction.op == "==":
                self._emit(f"JUMPZ {instruction.label}, {cond}")
            elif instruction.op == "!=":
                self._emit(f"JUMPNZ {instruction.label}, {cond}")
            else:
                raise RuntimeError(f"Unsupported cond jump: {instruction.op}")

        elif instruction.type == IRType.FUNCTION_CALL:
            self._emit_call(instruction)

        elif instruction.type == IRType.RETURN:
            if instruction.arg1 is not None:
                src = self._load_to_reg(instruction.arg1, "$AX")
                self._emit_epilogue(src)
            else:
                self._emit_epilogue(None)

        elif instruction.type == IRType.PRINT:
            self._emit_print_arg(instruction.arg1)

        elif instruction.type == IRType.READ:
            dst = self.slots[instruction.result]
            self._emit("READI $AX")
            self._emit(f"SET {dst}, $AX")

        elif instruction.type == IRType.NEW:
            self._emit_new(instruction)

        elif instruction.type == IRType.FIELD_GET:
            self._emit_field_get(instruction)

        elif instruction.type == IRType.FIELD_SET:
            self._emit_field_set(instruction)

        elif instruction.type == IRType.METHOD_CALL:
            self._emit_method_call(instruction)

    def _emit_dynamic_cast(self, src_reg: str, target: str, dst: str):
        """Runtime check that object's class is target or a subclass (§4.7.3).

        Incompatible casts intentionally touch chunk id 0 to raise interpreter
        error 28 as required by the specification.
        """
        ok_label = self._fresh_label("cast_ok")
        fail_label = self._fresh_label("cast_fail")
        allowed = self._runtime_cast_names(target)

        self._emit(f"# dynamic cast to {target}")
        # Null / undefined object (chunk id 0) is never a valid instance.
        self._emit(f"JUMPZ {fail_label}, {src_reg}")
        self._emit(f"GETWORD $BX, {src_reg}, 2")
        for cname in allowed:
            self._materialize_string(cname, "$CX")
            self._emit(f"EQS $DI, $BX, $CX")
            self._emit(f"JUMPNZ {ok_label}, $DI")
        self._emit(f"LABEL {fail_label}")
        self._emit("GETWORD $DI, 0, 0")
        self._emit(f"LABEL {ok_label}")
        self._emit(f"SET {dst}, {src_reg}")

    def _emit_new(self, instruction: IRInstruction):
        class_name = instruction.arg1
        info = self.classes[class_name]
        dst = self.slots[instruction.result]
        vmt_idx = self.class_order.index(class_name)
        parent = info.parent
        parent_idx = self.class_order.index(parent.name) if parent else 0
        size = info.object_size()
        self._emit(f"# new {class_name}")
        self._emit(f"CREATE $AX, {size}")
        self._emit(f"SETWORD $AX, 0, [{vmt_idx}]")
        self._emit(f"SETWORD $AX, 1, [{parent_idx}]")
        self._emit(f'SETWORD $AX, 2, "{class_name}"')
        # Default-init fields
        for i, (fname, ftype) in enumerate(info.all_fields().items()):
            offset = HEADER_SIZE + i
            if ftype == "string":
                self._materialize_string("", "$DI")
                self._emit(f"SETWORD $AX, {offset}, $DI")
            else:
                self._emit(f"SETWORD $AX, {offset}, 0")
        self._emit(f"SET {dst}, $AX")
        # Constructor chain: push this, call each ctor
        for ctor in info.constructor_chain():
            self._emit("ADDI $SP, $SP, 1")
            self._emit(f"SET [$SP], {dst}")
            self._emit(f"CALL [$SP+1], {ctor.label}")
            self._emit("SUBI $SP, $SP, 1")
        self.types[instruction.result] = class_name

    def _resolve_field_class(self, obj_operand: Any) -> ClassInfo:
        typ = self._type_of(obj_operand)
        if typ not in self.classes:
            # Fallback: try Object
            return self.classes.get("Object")
        return self.classes[typ]

    def _emit_field_get(self, instruction: IRInstruction):
        obj = instruction.arg1
        field = instruction.arg2
        dst = self.slots[instruction.result]
        info = self._resolve_field_class(obj)
        offset = info.field_offset(field)
        obj_op = self._load_to_reg(obj, "$OBJ")
        self._emit(f"GETWORD $AX, {obj_op}, {offset}")
        self._emit(f"SET {dst}, $AX")
        ftype = info.all_fields().get(field, "int")
        self.types[instruction.result] = ftype

    def _emit_field_set(self, instruction: IRInstruction):
        obj = instruction.arg1
        field = instruction.op
        value = instruction.arg2
        info = self._resolve_field_class(obj)
        offset = info.field_offset(field)
        obj_op = self._load_to_reg(obj, "$OBJ")
        val_op = self._load_to_reg(value, "$AX")
        ftype = info.all_fields().get(field, "int") if info else "int"
        if ftype == "string":
            self._emit(f"COPY $DI, {val_op}")
            self._emit(f"SETWORD {obj_op}, {offset}, $DI")
        else:
            self._emit(f"SETWORD {obj_op}, {offset}, {val_op}")

    def _emit_method_call(self, instruction: IRInstruction):
        obj = instruction.arg1
        method_name = instruction.op
        meta = instruction.arg2 or {}
        args = meta.get("args") or []
        is_super = meta.get("super", False)
        static_type = meta.get("static_type") or self._type_of(obj)
        info = self.classes.get(static_type) or self.classes.get("Object")
        result = instruction.result

        # Push this, then args (callee epilogue restores to this/return slot)
        self._push_value(obj)
        self._emit("SET $OBJ, [$SP]")
        for arg in args:
            self._push_value(arg)

        vmt_word = 1 if is_super else 0
        lookup = info.parent if (is_super and info and info.parent) else info
        if lookup is None or method_name not in lookup.vmt():
            raise RuntimeError(
                f"Unknown method '{method_name}' on type "
                f"'{getattr(lookup, 'name', static_type)}'"
            )
        method_idx = lookup.vmt_index(method_name)
        method = lookup.vmt().get(method_name)

        self._emit(f"GETWORD $AX, $OBJ, {vmt_word}")
        self._emit(f"GETWORD $AX, $AX, {method_idx}")
        self._emit("CALL [$SP+1], $AX")
        if result:
            self._emit("SET $AX, [$SP]")
            self._emit(f"SET {self.slots[result]}, $AX")
            if method:
                self.types[result] = method.return_type
        self._emit("SUBI $SP, $SP, 1")

    def _emit_object_helpers(self):
        # Object:toString - convert this chunk id to string
        self._emit("LABEL Object:toString")
        self._emit("INT2STRING $AX, [$SP]")
        self._emit("SET [$SP], $AX")
        self._emit("RETURN [$SP+1]")
        self._emit()
        # Object:getClass - word 2 of object
        self._emit("LABEL Object:getClass")
        self._emit("GETWORD $AX, [$SP], 2")
        self._emit("SET [$SP], $AX")
        self._emit("RETURN [$SP+1]")
        self._emit()

    def _emit_binary(self, instruction: IRInstruction):
        dst = self.slots[instruction.result]
        op = instruction.op

        if op == "CONCAT":
            # Push left, right; call helper
            self._push_value(instruction.arg1)
            self._push_value(instruction.arg2)
            self._emit("CALL [$SP+1], __str_concat__")
            self._emit("SET $AX, [$SP]")
            self._emit(f"SET {dst}, $AX")
            self._emit("SUBI $SP, $SP, 1")
            return

        # String comparisons
        if op in ("EQS", "NES", "LTS", "GTS", "LES", "GES"):
            self._load_to_reg(instruction.arg1, "$BX")
            self._load_to_reg(instruction.arg2, "$CX")
            if op == "EQS":
                self._emit("EQS $AX, $BX, $CX")
            elif op == "NES":
                self._emit("EQS $AX, $BX, $CX")
                self._emit("NOT $AX, $AX")
            elif op == "LTS":
                self._emit("LTS $AX, $BX, $CX")
            elif op == "GTS":
                self._emit("GTS $AX, $BX, $CX")
            elif op == "LES":
                self._emit("GTS $AX, $BX, $CX")
                self._emit("NOT $AX, $AX")
            elif op == "GES":
                self._emit("LTS $AX, $BX, $CX")
                self._emit("NOT $AX, $AX")
            self._emit(f"SET {dst}, $AX")
            return

        a = self._operand(instruction.arg1)
        b = self._operand(instruction.arg2)
        if a is None:
            a = self._load_to_reg(instruction.arg1, "$BX")
        if b is None:
            b = self._load_to_reg(instruction.arg2, "$CX")

        op_map = {
            "+": "ADDI",
            "-": "SUBI",
            "*": "MULI",
            "/": "DIVI",
            "==": "EQI",
            "<": "LTI",
            ">": "GTI",
            "&&": "AND",
            "||": "OR",
        }
        if op == "!=":
            self._emit(f"EQI $AX, {a}, {b}")
            self._emit("NOT $AX, $AX")
        elif op == "<=":
            self._emit(f"GTI $AX, {a}, {b}")
            self._emit("NOT $AX, $AX")
        elif op == ">=":
            self._emit(f"LTI $AX, {a}, {b}")
            self._emit("NOT $AX, $AX")
        elif op in op_map:
            self._emit(f"{op_map[op]} $AX, {a}, {b}")
        else:
            raise RuntimeError(f"Unsupported operator: {op}")
        self._emit(f"SET {dst}, $AX")

    def _push_value(self, value: Any):
        if self._is_str_lit(value):
            self._materialize_string(value[1], "$AX")
            self._emit("ADDI $SP, $SP, 1")
            self._emit("SET [$SP], $AX")
        else:
            src = self._operand(value)
            if src is None:
                src = self._load_to_reg(value, "$AX")
            self._emit("ADDI $SP, $SP, 1")
            self._emit(f"SET [$SP], {src}")

    def _emit_print_arg(self, arg: Any):
        if self._is_str_lit(arg):
            self._materialize_string(arg[1], "$AX")
            self._emit("WRITES $AX")
        elif self._type_of(arg) == "string":
            src = self._load_to_reg(arg, "$AX")
            self._emit(f"WRITES {src}")
        else:
            src = self._operand(arg)
            if src is None:
                src = self._load_to_reg(arg, "$AX")
            self._emit(f"WRITEI {src}")

    def _emit_call(self, instruction: IRInstruction):
        func_name = instruction.arg1
        args = instruction.arg2 or []
        result = instruction.result

        if func_name == "print":
            for arg in args:
                self._emit_print_arg(arg)
            return

        if func_name == "readInt":
            self._emit("READI $AX")
            if result:
                self._emit(f"SET {self.slots[result]}, $AX")
            return

        if func_name == "readString":
            self._emit("READS $AX")
            if result:
                self._emit(f"SET {self.slots[result]}, $AX")
                self.types[result] = "string"
            return

        if func_name == "length":
            # helper expects arg at [$SP], PC at [$SP+1]
            self._push_value(args[0])
            self._emit("CALL [$SP+1], length")
            if result:
                self._emit("SET $AX, [$SP]")
                self._emit(f"SET {self.slots[result]}, $AX")
            self._emit("SUBI $SP, $SP, 1")
            return

        if func_name == "subStr":
            # push s, i, n
            for arg in args:
                self._push_value(arg)
            self._emit("CALL [$SP+1], subStr")
            if result:
                self._emit("SET $AX, [$SP]")
                self._emit(f"SET {self.slots[result]}, $AX")
                self.types[result] = "string"
            self._emit("SUBI $SP, $SP, 1")
            return

        # User-defined function
        meta = self.func_meta.get(func_name, {})
        nparams = len(meta.get("params") or [])
        if nparams == 0:
            self._emit("ADDI $SP, $SP, 1")
            self._emit("SET [$SP], 0")
        else:
            for arg in args:
                self._push_value(arg)
        self._emit(f"CALL [$SP+1], {func_name}")
        if result:
            self._emit("SET $AX, [$SP]")
            self._emit(f"SET {self.slots[result]}, $AX")
            ret = meta.get("return_type", "int")
            self.types[result] = ret
        self._emit("SUBI $SP, $SP, 1")

    def _emit_length_helper(self):
        self._emit("LABEL length")
        self._emit("GETSIZE $AX, [$SP]")
        self._emit("SET [$SP], $AX")
        self._emit("RETURN [$SP+1]")
        self._emit()

    def _emit_substr_helper(self):
        # Reference implementation adapted to comma syntax
        self._emit("LABEL subStr")
        self._emit("CREATE $DI, 1")
        self._emit('SETWORD $DI, 0, ""')
        self._emit("GETWORD $DI, $DI, 0")
        self._emit("LTI $AX, [$SP-1], 0")
        self._emit("JUMPNZ subStr_end, $AX")
        self._emit("LTI $AX, [$SP], 0")
        self._emit("JUMPNZ subStr_end, $AX")
        self._emit("GETSIZE $AX, [$SP-2]")
        self._emit("LTI $EX, [$SP-1], $AX")
        self._emit("NOT $EX, $EX")
        self._emit("JUMPNZ subStr_end, $EX")
        self._emit("ADDI $EX, [$SP-1], [$SP]")
        self._emit("GETSIZE $AX, [$SP-2]")
        self._emit("GTI $CX, $EX, $AX")
        self._emit("JUMPZ subStr_min_end, $CX")
        self._emit("SUBI $EX, $AX, [$SP-1]")
        self._emit("SET [$SP], $EX")
        self._emit("LABEL subStr_min_end")
        self._emit("CREATE $DI, [$SP]")
        self._emit("SET $CX, 0")
        self._emit("SET $BX, [$SP-1]")
        self._emit("LABEL subStr_start_while")
        self._emit("LTI $EX, $CX, [$SP]")
        self._emit("JUMPZ subStr_end, $EX")
        self._emit("GETWORD $AX, [$SP-2], $BX")
        self._emit("SETWORD $DI, $CX, $AX")
        self._emit("ADDI $CX, $CX, 1")
        self._emit("ADDI $BX, $BX, 1")
        self._emit("JUMP subStr_start_while")
        self._emit("LABEL subStr_end")
        self._emit("SUBI $SP, $SP, 2")
        self._emit("SET [$SP], $DI")
        self._emit("RETURN [$SP+3]")
        self._emit()

    def _emit_concat_helper(self):
        self._emit("LABEL __str_concat__")
        self._emit("SUBI $SP, $SP, 1")
        self._emit("GETSIZE $BX, [$SP]")
        self._emit("GETSIZE $EX, [$SP+1]")
        self._emit("COPY $DI, [$SP]")
        self._emit("ADDI $AX, $BX, $EX")
        self._emit("RESIZE $DI, $AX")
        self._emit("SET $CX, 0")
        self._emit("LABEL __str_concat__loop")
        self._emit("LTI $AX, $CX, $EX")
        self._emit("JUMPZ __str_concat__end, $AX")
        self._emit("GETWORD $SI, [$SP+1], $CX")
        self._emit("SETWORD $DI, $BX, $SI")
        self._emit("ADDI $BX, $BX, 1")
        self._emit("ADDI $CX, $CX, 1")
        self._emit("JUMP __str_concat__loop")
        self._emit("LABEL __str_concat__end")
        self._emit("SET [$SP], $DI")
        self._emit("RETURN [$SP+2]")
        self._emit()
